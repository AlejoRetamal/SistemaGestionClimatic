const { hashPin, pinLookup, validPin } = require("../services/pin.service");
const VERSION = "translated-schema-auth-v1";

// Explicit, atomic migration of the translated schema; never runs at server startup.
// PINs are read only to hash them, never logged or used to impersonate an employee.
async function preparePostgresAuth(db, config) {
  const secretCheck = pinLookup("climatic-auth-migration-v1", config.pinSecret);
  const client = await db.connect();
  try {
    await client.query("BEGIN");
    await client.query("SET LOCAL lock_timeout = '10s'");
    await client.query("SELECT pg_advisory_xact_lock(783241902)");
    await client.query("LOCK TABLE public.empleados IN ACCESS EXCLUSIVE MODE");
    await client.query(`CREATE TABLE IF NOT EXISTS public.climatic_migrations (
      version TEXT PRIMARY KEY, secret_check TEXT NOT NULL,
      applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )`);
    const { rows: applied } = await client.query(
      "SELECT secret_check FROM public.climatic_migrations WHERE version=$1",
      [VERSION],
    );
    if (applied.length) {
      if (applied[0].secret_check !== secretCheck)
        throw new Error(
          "APP_PIN_SECRET difiere del usado al migrar. Restaurá el secreto original.",
        );
      await client.query(
        "SELECT pin_hash,pin_lookup FROM public.empleados LIMIT 0",
      );
      await client.query(
        "SELECT token_hash,csrf_hash FROM public.sesiones LIMIT 0",
      );
      await client.query("COMMIT");
      return { alreadyApplied: true, migrated: 0 };
    }
    const { rows: columns } =
      await client.query(`SELECT column_name FROM information_schema.columns
      WHERE table_schema='public' AND table_name='empleados'`);
    if (
      !columns.some((c) => c.column_name === "pin") ||
      columns.some((c) => ["pin_hash", "pin_lookup"].includes(c.column_name))
    )
      throw new Error(
        "Se requiere el esquema traducido con empleados.pin y sin migración parcial.",
      );
    // Verify that this is the maintenance schema, not the old auth-only prototype.
    await client.query("SELECT plan_id FROM public.proximos_servicios LIMIT 0");
    await client.query(
      "SELECT registro_tarea_id FROM public.registro_tareas_repuestos LIMIT 0",
    );
    await client.query(`ALTER TABLE public.empleados
      ADD COLUMN pin_hash TEXT CHECK (pin_hash ~ '^scrypt:[a-f0-9]{32}:[a-f0-9]{128}$'),
      ADD COLUMN pin_lookup TEXT UNIQUE CHECK (pin_lookup ~ '^[a-f0-9]{64}$')`);
    const { rows: employees } = await client.query(
      "SELECT id,pin FROM public.empleados ORDER BY id",
    );
    for (const employee of employees) {
      const pin = employee.pin.trimEnd(); // CHAR padding only; preserve leading zeroes.
      if (!validPin(pin))
        throw new Error("Hay PIN no numéricos. La migración se revirtió.");
      await client.query(
        "UPDATE public.empleados SET pin_hash=$1,pin_lookup=$2 WHERE id=$3",
        [await hashPin(pin), pinLookup(pin, config.pinSecret), employee.id],
      );
    }
    await client.query(`ALTER TABLE public.empleados
      ALTER COLUMN pin_hash SET NOT NULL, ALTER COLUMN pin_lookup SET NOT NULL,
      DROP COLUMN pin`);
    await client.query(`CREATE TABLE public.sesiones (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      empleado_id BIGINT NOT NULL REFERENCES public.empleados(id) ON UPDATE CASCADE ON DELETE RESTRICT,
      token_hash TEXT NOT NULL UNIQUE CHECK (token_hash ~ '^[a-f0-9]{64}$'),
      csrf_hash TEXT NOT NULL CHECK (csrf_hash ~ '^[a-f0-9]{64}$'),
      fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
      fecha_expiracion TIMESTAMPTZ NOT NULL CHECK (fecha_expiracion > fecha_creacion)
    );
    CREATE INDEX sesiones_empleado_idx ON public.sesiones(empleado_id);
    CREATE INDEX sesiones_expiracion_idx ON public.sesiones(fecha_expiracion);
    ALTER TABLE public.sesiones ENABLE ROW LEVEL SECURITY;
    ALTER TABLE public.climatic_migrations ENABLE ROW LEVEL SECURITY;
    REVOKE ALL ON public.sesiones,public.climatic_migrations FROM PUBLIC;
    REVOKE ALL ON SEQUENCE public.sesiones_id_seq FROM PUBLIC;
    DO $$ DECLARE role_name TEXT; BEGIN
      FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
          EXECUTE format('REVOKE ALL ON public.sesiones,public.climatic_migrations FROM %I', role_name);
          EXECUTE format('REVOKE ALL ON SEQUENCE public.sesiones_id_seq FROM %I', role_name);
        END IF;
      END LOOP;
    END $$;`);
    await client.query(
      "INSERT INTO public.climatic_migrations(version,secret_check) VALUES ($1,$2)",
      [VERSION, secretCheck],
    );
    await client.query("COMMIT");
    return { alreadyApplied: false, migrated: employees.length };
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}
module.exports = { preparePostgresAuth };
