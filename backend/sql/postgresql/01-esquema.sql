-- FECHA DE BAJA Y CIERRE
CREATE FUNCTION public.climatic_maquinas_fecha_baja()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    IF NEW.status = 'No Activo' AND OLD.status = 'Activo' THEN
        NEW.fecha_baja := statement_timestamp() AT TIME ZONE 'America/Argentina/Buenos_Aires';
    ELSIF NEW.status = 'Activo' AND OLD.status = 'No Activo' THEN
        NEW.fecha_baja := NULL;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_maquinas_fecha_baja BEFORE UPDATE ON public.maquinas
FOR EACH ROW EXECUTE FUNCTION public.climatic_maquinas_fecha_baja();

CREATE FUNCTION public.climatic_ordenes_fecha_cierre()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    IF NOT NEW.activo AND OLD.activo THEN
        NEW.fecha_cierre := statement_timestamp() AT TIME ZONE 'America/Argentina/Buenos_Aires';
    ELSIF NEW.activo AND NOT OLD.activo THEN
        NEW.fecha_cierre := NULL;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_ordenes_fecha_cierre BEFORE UPDATE ON public.ordenes_mantenimiento
FOR EACH ROW EXECUTE FUNCTION public.climatic_ordenes_fecha_cierre();

-- HOROMETRO: se conserva la actualizacion por la tarea del registro.
CREATE FUNCTION public.climatic_registro_tareas_horas()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    IF NEW.medicion_horometro IS NOT NULL THEN
        UPDATE public.maquinas
        SET horas = NEW.medicion_horometro
        WHERE id = (SELECT maquina_id FROM public.tareas WHERE id = NEW.tarea_id);
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_registro_tareas_horas_insert AFTER INSERT ON public.registro_tareas
FOR EACH ROW EXECUTE FUNCTION public.climatic_registro_tareas_horas();
CREATE TRIGGER trg_registro_tareas_horas_update AFTER UPDATE ON public.registro_tareas
FOR EACH ROW
WHEN (NEW.medicion_horometro IS NOT NULL AND NEW.medicion_horometro IS DISTINCT FROM OLD.medicion_horometro)
EXECUTE FUNCTION public.climatic_registro_tareas_horas();

-- COMPATIBILIDAD Y STOCK: el bloqueo se mantiene hasta terminar la transaccion.
CREATE FUNCTION public.climatic_registro_repuestos_validar_insert()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
DECLARE
    v_maquina_tarea BIGINT;
    v_maquina_repuesto BIGINT;
    v_stock NUMERIC(12,2);
BEGIN
    SELECT t.maquina_id INTO v_maquina_tarea
    FROM public.registro_tareas rt JOIN public.tareas t ON t.id = rt.tarea_id
    WHERE rt.id = NEW.registro_tarea_id;

    SELECT maquina_id INTO v_maquina_repuesto
    FROM public.repuestos WHERE id = NEW.repuesto_id;

    IF v_maquina_tarea IS NULL OR v_maquina_repuesto IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001',
            MESSAGE = 'No se pudo determinar la maquina del registro o del repuesto';
    END IF;
    IF v_maquina_tarea <> v_maquina_repuesto THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001',
            MESSAGE = 'El repuesto no pertenece a la maquina de la tarea';
    END IF;

    SELECT cantidad_actual INTO v_stock FROM public.inventario
    WHERE repuesto_id = NEW.repuesto_id FOR UPDATE;
    IF v_stock IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'El repuesto no posee registro de inventario';
    END IF;
    IF v_stock < NEW.cantidad THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Stock insuficiente';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_registro_repuestos_validar_insert BEFORE INSERT ON public.registro_tareas_repuestos
FOR EACH ROW EXECUTE FUNCTION public.climatic_registro_repuestos_validar_insert();

CREATE FUNCTION public.climatic_registro_repuestos_descontar()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    UPDATE public.inventario SET cantidad_actual = cantidad_actual - NEW.cantidad
    WHERE repuesto_id = NEW.repuesto_id;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_registro_repuestos_descontar AFTER INSERT ON public.registro_tareas_repuestos
FOR EACH ROW EXECUTE FUNCTION public.climatic_registro_repuestos_descontar();

CREATE FUNCTION public.climatic_registro_repuestos_devolver()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    -- PostgreSQL dispara este trigger tambien en ON DELETE CASCADE; MySQL no.
    -- Mantener el comportamiento original: devolver solo al borrar directamente el detalle.
    IF EXISTS (SELECT 1 FROM public.registro_tareas WHERE id = OLD.registro_tarea_id) THEN
        UPDATE public.inventario SET cantidad_actual = cantidad_actual + OLD.cantidad
        WHERE repuesto_id = OLD.repuesto_id;
    END IF;
    RETURN OLD;
END;
$$;
CREATE TRIGGER trg_registro_repuestos_devolver AFTER DELETE ON public.registro_tareas_repuestos
FOR EACH ROW EXECUTE FUNCTION public.climatic_registro_repuestos_devolver();

-- La vista mantiene las formulas del script MySQL, incluidos los MAX independientes.
CREATE VIEW public.proximos_servicios WITH (security_invoker = true) AS
SELECT
    CONCAT('PRE-', pp.id) AS plan_key,
    pp.id AS plan_id,
    'Preventivo'::TEXT AS tipo,
    pp.frecuencia,
    t.id AS tarea_id,
    t.nombre AS tarea_nombre,
    t.descripcion AS tarea_descripcion,
    m.id AS maquina_id,
    m.nombre AS maquina_nombre,
    (SELECT MAX(rt.medicion_horometro) FROM public.registro_tareas rt WHERE rt.tarea_id = t.id) AS ultimo_horometro,
    (SELECT MAX(rt.duracion_fin) FROM public.registro_tareas rt WHERE rt.tarea_id = t.id) AS ultima_fecha_ejecucion,
    COALESCE((SELECT MAX(rt.medicion_horometro) FROM public.registro_tareas rt WHERE rt.tarea_id = t.id), m.horas, 0) + pp.frecuencia AS proximo_servicio
FROM public.plan_preventivo pp
JOIN public.tareas t ON t.id = pp.tarea_id
JOIN public.maquinas m ON m.id = t.maquina_id
UNION ALL
SELECT
    CONCAT('PRED-', pd.id) AS plan_key,
    pd.id AS plan_id,
    'Predictivo'::TEXT AS tipo,
    pd.frecuencia,
    t.id AS tarea_id,
    t.nombre AS tarea_nombre,
    t.descripcion AS tarea_descripcion,
    m.id AS maquina_id,
    m.nombre AS maquina_nombre,
    (SELECT MAX(rt.medicion_horometro) FROM public.registro_tareas rt WHERE rt.tarea_id = t.id) AS ultimo_horometro,
    (SELECT MAX(rt.duracion_fin) FROM public.registro_tareas rt WHERE rt.tarea_id = t.id) AS ultima_fecha_ejecucion,
    COALESCE((SELECT MAX(rt.medicion_horometro) FROM public.registro_tareas rt WHERE rt.tarea_id = t.id), m.horas, 0) + pd.frecuencia AS proximo_servicio
FROM public.plan_predictivo pd
JOIN public.tareas t ON t.id = pd.tarea_id
JOIN public.maquinas m ON m.id = t.maquina_id;

-- Acceso exclusivo por backend/propietario; no se usan usuarios Supabase Auth.
-- Estas restricciones se limitan a los objetos creados por este archivo.
DO $$
DECLARE
    object_name TEXT;
    role_name TEXT;
    sequence_name TEXT;
BEGIN
    FOREACH object_name IN ARRAY ARRAY[
        'empleados', 'maquinas', 'proveedores', 'repuestos', 'repuestos_proveedores',
        'inventario', 'tareas', 'tareas_extraordinarias', 'plan_preventivo',
        'plan_predictivo', 'ordenes_mantenimiento', 'registro_tareas', 'registro_tareas_repuestos'
    ] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', object_name);
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC', object_name);
        sequence_name := NULL;
        IF object_name <> 'repuestos_proveedores' THEN
            sequence_name := pg_get_serial_sequence('public.' || object_name, 'id');
            EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC', sequence_name);
        END IF;
        FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
                EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I', object_name, role_name);
                IF sequence_name IS NOT NULL THEN
                    EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM %I', sequence_name, role_name);
                END IF;
            END IF;
        END LOOP;
    END LOOP;
    REVOKE ALL ON TABLE public.proximos_servicios FROM PUBLIC;
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
            EXECUTE format('REVOKE ALL ON TABLE public.proximos_servicios FROM %I', role_name);
        END IF;
    END LOOP;
    FOREACH object_name IN ARRAY ARRAY[
        'climatic_maquinas_fecha_baja', 'climatic_ordenes_fecha_cierre', 'climatic_registro_tareas_horas',
        'climatic_registro_repuestos_validar_insert', 'climatic_registro_repuestos_descontar',
        'climatic_registro_repuestos_devolver'
    ] LOOP
        EXECUTE format('REVOKE ALL ON FUNCTION public.%I() FROM PUBLIC', object_name);
        FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
                EXECUTE format('REVOKE ALL ON FUNCTION public.%I() FROM %I', object_name, role_name);
            END IF;
        END LOOP;
    END LOOP;
END;
$$;
COMMIT;
